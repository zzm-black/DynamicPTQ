def deploy_real_int4_flatquant(model: torch.nn.Module, fq_args, cfg: UnifiedRunConfig) -> Dict[str, int]:
    if fq_args.w_bits != 4 or fq_args.a_bits != 4:
        raise ValueError(
            "Real FlatQuant deploy backend only supports W4A4. "
            f"Got w_bits={fq_args.w_bits}, a_bits={fq_args.a_bits}."
        )
    if fq_args.w_asym or fq_args.a_asym:
        raise ValueError("Real FlatQuant deploy backend requires symmetric weight and activation quantization.")

    import gptq_utils
    import flatquant.utils as fq_utils
    try:
        from deploy.nn.linear import Linear4bit
        from deploy.nn.quantization import Quantizer
    except ModuleNotFoundError as error:
        if error.name == "deploy._CUDA":
            raise RuntimeError(
                "FlatQuant real INT4 inference requires the compiled deploy._CUDA extension. "
                "Build it with: python -m pip install --no-build-isolation -e ${WORKSPACE_ROOT}/FlatQuant"
            ) from error
        raise
    from flatquant.flat_linear import FlatQuantizedLinear

    deep_layer_ids: set[int] = set()
    if cfg.enable_deep and int(cfg.deep_act_bits) != 4:
        deep_layer_ids = set(int(x) for x in cfg.deep_layers.split(",") if x.strip())

    # The FlatQuant deploy kernels assert FP16 activations/scales.
    model.to(dtype=torch.float16)

    for module_name, module in list(model.named_modules()):
        if not isinstance(module, FlatQuantizedLinear):
            continue
        match = re.search(r"model\.layers\.(\d+)\.", module_name)
        layer_idx = int(match.group(1)) if match else None
        if layer_idx in deep_layer_ids:
            continue
        if int(module.act_quantizer.bits) != 4:
            raise ValueError(
                "Real FlatQuant deploy backend only supports 4-bit activations. "
                f"Module {module_name} has {module.act_quantizer.bits}-bit activation. "
                "Set DEEP_ACT_BITS=4 for this real-quant benchmark."
            )

    quantizers = gptq_utils.rtn_fwrd(model, fq_utils.DEV, fq_args)

    converted_linears = 0
    converted_activations = 0
    deep_kept_fp_linears = 0
    for module_name, module in list(model.named_modules()):
        if not isinstance(module, FlatQuantizedLinear):
            continue

        match = re.search(r"model\.layers\.(\d+)\.", module_name)
        layer_idx = int(match.group(1)) if match else None
        if layer_idx in deep_layer_ids:
            # Keep these DEEP layers on original activation path (e.g. 8-bit) instead of forcing INT4 input quantizer.
            deep_kept_fp_linears += 1
            continue

        linear_name = f"{module_name}.linear"
        weight_quantizer = quantizers.get(linear_name)
        if weight_quantizer is None:
            continue

        deploy_activation_quantizer = Quantizer(lac=bool(fq_args.lac))
        if hasattr(module.act_quantizer, "clip_factor_a_max"):
            deploy_activation_quantizer.clip_factor_a_max.fill_(
                float(module.act_quantizer.clip_factor_a_max.detach().cpu().reshape(-1)[0])
            )
            deploy_activation_quantizer.clip_factor_a_min.fill_(
                float(module.act_quantizer.clip_factor_a_min.detach().cpu().reshape(-1)[0])
            )

        int4_linear = Linear4bit.from_float(module.linear, weight_scales=weight_quantizer.scale)
        module.linear = nn.Sequential(deploy_activation_quantizer, int4_linear)
        module.act_quantizer.enable = False
        converted_linears += 1
        converted_activations += 1

    if converted_linears == 0:
        raise RuntimeError("No FlatQuant linear modules were converted to real INT4 deployment.")

    return {
        "converted_int4_linears": converted_linears,
        "converted_int4_activation_quantizers": converted_activations,
        "deep_layers_kept_original_activation_path": deep_kept_fp_linears,
        "quantizer_count": len(quantizers),
    }


def load_benchmark_model(args: argparse.Namespace, enable_deep: bool):
    runner = UnifiedPTQRunner()
    cfg = build_config(args, enable_deep=enable_deep)
    runner._prepare_import_path(cfg.workspace_root / "FlatQuant")

    import flatquant.flat_utils as fq_flat_utils
    import flatquant.model_utils as fq_model_utils
    import flatquant.utils as fq_utils

    transformers.set_seed(cfg.seed)
    fq_utils.seed_everything(seed=cfg.seed)

    model, apply_flatquant = fq_model_utils.get_model(cfg.model_path, cfg.hf_token)
    fq_args = runner._build_flatquant_args(cfg)
    model = apply_flatquant(fq_args, model)
    runner._apply_deep_activation_bits(model, cfg)
    adapter = runner._build_adapter(cfg)
    toolkit = runner._build_toolkit(cfg, len(model.model.layers))

    LOGGER.info("Loading FlatQuant parameters from %s", cfg.flat_parameters_path)
    fq_flat_utils.load_flat_parameters(fq_args, model, path=cfg.flat_parameters_path)
    runner._apply_deep_activation_bits(model, cfg)
    toolkit.run_post_calib(model, adapter)

    if args.real_quant:
        deploy_stats = deploy_real_int4_flatquant(model, fq_args, cfg)
        LOGGER.info("Real INT4 deployment enabled: %s", deploy_stats)

    model.eval()
    model.config.use_cache = True
    if cfg.distribute_model:
        fq_utils.distribute_model(model)
    else:
        model.to(fq_utils.DEV)

    bit_histogram, per_layer_bits = collect_activation_bit_stats(model)
    LOGGER.info(
        "DEEP switch check enable_deep=%s: activation_bit_histogram=%s, per_layer_bits=%s",
        cfg.enable_deep,
        bit_histogram,
        per_layer_bits,
    )
    return model


def result_paths(args: argparse.Namespace) -> Tuple[Path, Path]:
    output_dir = Path(args.output_dir).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    return output_dir / f"{args.exp_name}.jsonl", output_dir / f"{args.exp_name}.csv"


def append_jsonl(path: Path, row: Dict[str, object]) -> None:
    with path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(row, ensure_ascii=False) + "\n")


def write_csv(path: Path, rows: List[Dict[str, object]]) -> None:
    if not rows:
        return
    fieldnames = sorted({key for row in rows for key in row.keys()})
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def benchmark_variant(args: argparse.Namespace, variant: str, enable_deep: bool, jsonl_path: Path) -> List[Dict[str, object]]:
    LOGGER.info("Benchmarking variant=%s", variant)
    model = load_benchmark_model(args, enable_deep=enable_deep)
    rows: List[Dict[str, object]] = []

    for batch_size in args.batch_sizes:
        LOGGER.info("Running %s batch_size=%d prefill", variant, batch_size)
        cleanup_cuda()
        try:
            prefill_memory, prefill_times = benchmark_callable(
                lambda: run_prefill_once(model, batch_size, args.prefill_seq_len),
                warmup_steps=args.warmup_steps,
                repeat_steps=args.repeat_steps,
            )
        except torch.cuda.OutOfMemoryError as error:
            cleanup_cuda()
            oom_row: Dict[str, object] = {
                "variant": variant,
                "enable_deep": enable_deep,
                "stage": "prefill",
                "batch_size": batch_size,
                "prefill_seq_len": args.prefill_seq_len,
                "decode_steps": 0,
                "tokens": batch_size * args.prefill_seq_len,
                "status": "oom",
                "error": str(error).splitlines()[0],
            }
            append_jsonl(jsonl_path, oom_row)
            rows.append(oom_row)
            LOGGER.warning(
                "%s prefill bsz=%d OOM; skipping this batch. error=%s",
                variant,
                batch_size,
                oom_row["error"],
            )
            if args.skip_oom:
                continue
            raise
        prefill_summary = summarize_times(prefill_times)
        prefill_row: Dict[str, object] = {
            "variant": variant,
            "enable_deep": enable_deep,
            "stage": "prefill",
            "batch_size": batch_size,
            "prefill_seq_len": args.prefill_seq_len,
            "decode_steps": 0,
            "tokens": batch_size * args.prefill_seq_len,
            "tokens_per_second": (batch_size * args.prefill_seq_len) / (prefill_summary["time_ms_mean"] / 1000.0),
            **prefill_summary,
            **prefill_memory,
        }
        append_jsonl(jsonl_path, prefill_row)
        rows.append(prefill_row)
        LOGGER.info(
            "%s prefill bsz=%d: %.3f ms, %.2f tok/s, peak=%.2f GB",
            variant,
            batch_size,
            prefill_row["time_ms_mean"],
            prefill_row["tokens_per_second"],
            prefill_row.get("total_peak_allocated_gb", 0.0),
        )

        LOGGER.info("Running %s batch_size=%d decode", variant, batch_size)
        try:
            decode_memory, decode_times = benchmark_decode(
                model=model,
                batch_size=batch_size,
                prefill_seq_len=args.prefill_seq_len,
                decode_steps=args.decode_steps,
                warmup_steps=args.warmup_steps,
                repeat_steps=args.repeat_steps,
            )
        except torch.cuda.OutOfMemoryError as error:
            cleanup_cuda()
            oom_row = {
                "variant": variant,
                "enable_deep": enable_deep,
                "stage": "decode",
                "batch_size": batch_size,
                "prefill_seq_len": args.prefill_seq_len,
                "decode_steps": args.decode_steps,
                "tokens": batch_size * args.decode_steps,
                "status": "oom",
                "error": str(error).splitlines()[0],
            }
            append_jsonl(jsonl_path, oom_row)
            rows.append(oom_row)
            LOGGER.warning(
                "%s decode bsz=%d OOM; skipping this batch. error=%s",
                variant,
                batch_size,
                oom_row["error"],
            )
            if args.skip_oom:
                continue
            raise
        decode_summary = summarize_times(decode_times)
        decode_row: Dict[str, object] = {
            "variant": variant,
            "enable_deep": enable_deep,
            "stage": "decode",
            "batch_size": batch_size,
            "prefill_seq_len": args.prefill_seq_len,
            "decode_steps": args.decode_steps,
            "tokens": batch_size * args.decode_steps,
            "tokens_per_second": (batch_size * args.decode_steps) / (decode_summary["time_ms_mean"] / 1000.0),
            **decode_summary,
            **decode_memory,
        }
        append_jsonl(jsonl_path, decode_row)
        rows.append(decode_row)
        LOGGER.info(
            "%s decode bsz=%d: %.3f ms, %.2f tok/s, peak=%.2f GB",
            variant,
            batch_size,
            decode_row["time_ms_mean"],
            decode_row["tokens_per_second"],
            decode_row.get("total_peak_allocated_gb", 0.0),
        )
        cleanup_cuda()

    del model
    cleanup_cuda()
    return rows


def annotate_comparisons(rows: List[Dict[str, object]]) -> None:
    indexed = {
        (row["stage"], row["batch_size"], row["variant"]): row
        for row in rows
    }
    for row in rows:
        if row["variant"] != "deep":
            continue
        if row.get("status") == "oom" or "time_ms_mean" not in row:
            continue
        base = indexed.get((row["stage"], row["batch_size"], "no_deep"))
        if base is None or base.get("status") == "oom" or "time_ms_mean" not in base:
            continue
        row["speedup_vs_no_deep"] = float(base["time_ms_mean"]) / float(row["time_ms_mean"])
        base_peak = max(float(base.get("total_peak_allocated_gb", 0.0)), 1e-12)
        row["peak_memory_ratio_vs_no_deep"] = (
            float(row.get("total_peak_allocated_gb", 0.0)) / base_peak
        )


def main() -> None:
    args = parse_args()
    logging.basicConfig(level=logging.INFO, format="[%(asctime)s] %(levelname)s %(message)s")

    if not torch.cuda.is_available():
        raise RuntimeError("CUDA is required for latency and memory benchmarking.")
    if args.repeat_steps <= 0:
        raise ValueError("--repeat_steps must be positive.")
    if args.warmup_steps < 0:
        raise ValueError("--warmup_steps must be non-negative.")

    jsonl_path, csv_path = result_paths(args)
    if jsonl_path.exists():
        jsonl_path.unlink()

    rows: List[Dict[str, object]] = []
    try:
        if args.variant in ("both", "no_deep"):
            rows.extend(benchmark_variant(args, "no_deep", enable_deep=False, jsonl_path=jsonl_path))
        if args.variant in ("both", "deep"):
            rows.extend(benchmark_variant(args, "deep", enable_deep=True, jsonl_path=jsonl_path))
    except torch.cuda.OutOfMemoryError:
        LOGGER.exception("CUDA OOM. Reduce --batch_sizes, --prefill_seq_len, or use --distribute_model.")
        sys.exit(2)

    annotate_comparisons(rows)
    write_csv(csv_path, rows)
    LOGGER.info("Saved JSONL results to %s", jsonl_path)
    LOGGER.info("Saved CSV results to %s", csv_path)

    print(json.dumps({"jsonl": str(jsonl_path), "csv": str(csv_path)}, indent=2))


if __name__ == "__main__":
    main()
