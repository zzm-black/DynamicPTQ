def cleanup_cuda() -> None:
    gc.collect()
    if torch.cuda.is_available():
        torch.cuda.empty_cache()


def sync_cuda() -> None:
    if torch.cuda.is_available():
        for device_idx in range(torch.cuda.device_count()):
            torch.cuda.synchronize(device_idx)


def reset_peak_memory() -> None:
    if torch.cuda.is_available():
        for device_idx in range(torch.cuda.device_count()):
            torch.cuda.reset_peak_memory_stats(device_idx)


def collect_memory_stats() -> Dict[str, float]:
    stats: Dict[str, float] = {}
    if not torch.cuda.is_available():
        return stats

    allocated_values = []
    reserved_values = []
    peak_values = []
    for device_idx in range(torch.cuda.device_count()):
        allocated = torch.cuda.memory_allocated(device_idx) / (1024**3)
        reserved = torch.cuda.memory_reserved(device_idx) / (1024**3)
        peak = torch.cuda.max_memory_allocated(device_idx) / (1024**3)
        stats[f"gpu{device_idx}_allocated_gb"] = allocated
        stats[f"gpu{device_idx}_reserved_gb"] = reserved
        stats[f"gpu{device_idx}_peak_allocated_gb"] = peak
        allocated_values.append(allocated)
        reserved_values.append(reserved)
        peak_values.append(peak)

    stats["total_allocated_gb"] = float(sum(allocated_values))
    stats["total_reserved_gb"] = float(sum(reserved_values))
    stats["total_peak_allocated_gb"] = float(sum(peak_values))
    stats["max_gpu_peak_allocated_gb"] = float(max(peak_values)) if peak_values else 0.0
    return stats


def get_input_device(model: torch.nn.Module) -> torch.device:
    try:
        return model.get_input_embeddings().weight.device
    except AttributeError:
        return next(model.parameters()).device


def collect_activation_bit_stats(model: torch.nn.Module) -> Tuple[Dict[int, int], Dict[int, Dict[int, int]]]:
    histogram: Dict[int, int] = {}
    per_layer: Dict[int, Dict[int, int]] = {}
    layers = getattr(getattr(model, "model", None), "layers", [])
    for layer_idx, layer in enumerate(layers):
        layer_histogram: Dict[int, int] = {}
        for module in layer.modules():
            act_q = getattr(module, "act_quantizer", None)
            if act_q is None or not hasattr(act_q, "bits"):
                continue
            bits = int(act_q.bits)
            histogram[bits] = histogram.get(bits, 0) + 1
            layer_histogram[bits] = layer_histogram.get(bits, 0) + 1
        if layer_histogram:
            per_layer[layer_idx] = layer_histogram
    return histogram, per_layer


def make_input(batch_size: int, seq_len: int, device: torch.device) -> torch.Tensor:
    return torch.randint(100, 200, (batch_size, seq_len), dtype=torch.long, device=device)


@torch.no_grad()
def run_prefill_once(model: torch.nn.Module, batch_size: int, seq_len: int) -> None:
    input_ids = make_input(batch_size, seq_len, get_input_device(model))
    model(input_ids=input_ids, use_cache=True)


@torch.no_grad()
def build_past_key_values(model: torch.nn.Module, batch_size: int, seq_len: int):
    input_ids = make_input(batch_size, seq_len, get_input_device(model))
    output = model(input_ids=input_ids, use_cache=True)
    return output.past_key_values


@torch.no_grad()
def run_decode_once(model: torch.nn.Module, batch_size: int, past_key_values, decode_steps: int) -> None:
    device = get_input_device(model)
    next_token = torch.full((batch_size, 1), 100, dtype=torch.long, device=device)
    current_past = past_key_values
    for _ in range(decode_steps):
        output = model(input_ids=next_token, past_key_values=current_past, use_cache=True)
        current_past = output.past_key_values


def summarize_times(times_ms: Iterable[float]) -> Dict[str, float]:
    values = np.asarray(list(times_ms), dtype=np.float64)
    return {
        "time_ms_mean": float(values.mean()),
        "time_ms_std": float(values.std()),
        "time_ms_ci95": float(1.96 * values.std()),
    }


def benchmark_callable(fn, warmup_steps: int, repeat_steps: int) -> Tuple[Dict[str, float], List[float]]:
    for _ in range(warmup_steps):
        fn()
    sync_cuda()
    cleanup_cuda()
    reset_peak_memory()

    times_ms: List[float] = []
    for _ in range(repeat_steps):
        sync_cuda()
        start_time = time.perf_counter()
        fn()
        sync_cuda()
        times_ms.append((time.perf_counter() - start_time) * 1000.0)

    memory_stats = collect_memory_stats()
    return memory_stats, times_ms


def benchmark_decode(
    model: torch.nn.Module,
    batch_size: int,
    prefill_seq_len: int,
    decode_steps: int,
    warmup_steps: int,
    repeat_steps: int,
) -> Tuple[Dict[str, float], List[float]]:
    for _ in range(warmup_steps):
        past_key_values = build_past_key_values(model, batch_size, prefill_seq_len)
        sync_cuda()
        run_decode_once(model, batch_size, past_key_values, decode_steps)
        del past_key_values
        cleanup_cuda()

    times_ms: List[float] = []
    memory_stats: Dict[str, float] = {}
    for _ in range(repeat_steps):
        past_key_values = build_past_key_values(model, batch_size, prefill_seq_len)
        sync_cuda()
        cleanup_cuda()
        reset_peak_memory()

        start_time = time.perf_counter()
        run_decode_once(model, batch_size, past_key_values, decode_steps)
        sync_cuda()
        times_ms.append((time.perf_counter() - start_time) * 1000.0)
        memory_stats = collect_memory_stats()

        del past_key_values
        cleanup_cuda()

    return memory_stats, times_ms


